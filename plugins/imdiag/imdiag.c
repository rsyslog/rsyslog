/* get the first word delimited by space from a given string. The pointer is
 * advanced to after the word. Any leading spaces are discarded. If the
 * output buffer is too small, parsing ends on buffer full condition.
 * An empty buffer is returned if there is no more data inside the string.
 * rgerhards, 2009-05-27
 */
#define TO_LOWERCASE 1
#define NO_MODIFY 0
static void getFirstWord(uchar **ppszSrc, uchar *pszBuf, size_t lenBuf, int options) {
    uchar c;
    uchar *pszSrc = *ppszSrc;

    while (*pszSrc && *pszSrc == ' ') ++pszSrc; /* skip to first non-space */

    while (*pszSrc && *pszSrc != ' ' && lenBuf > 1) {
        c = *pszSrc++;
        if (options & TO_LOWERCASE) c = tolower(c);
        *pszBuf++ = c;
        lenBuf--;
    }

    *pszBuf = '\0';
    *ppszSrc = pszSrc;
}


/* send a response back to the originator
 * rgerhards, 2009-05-27
 */
static rsRetVal __attribute__((format(printf, 2, 3))) sendResponse(tcps_sess_t *pSess,
                                                                   const char *const __restrict__ fmt,
                                                                   ...) {
    va_list ap;
    ssize_t len;
    uchar buf[1024];
    DEFiRet;

    va_start(ap, fmt);
    len = vsnprintf((char *)buf, sizeof(buf), fmt, ap);
    va_end(ap);
    if (len < 0) {
        memcpy(buf, "imdiag::error formatting response failed\n", sizeof("imdiag::error formatting response failed\n"));
        len = sizeof("imdiag::error formatting response failed\n") - 1;
    } else if ((size_t)len >= sizeof(buf)) {
        len = sizeof(buf) - 1;
    }
    CHKiRet(netstrm.Send(pSess->pStrm, buf, &len));

finalize_it:
    RETiRet;
}

/* submit a generated numeric-suffix message to the rsyslog core
 */
static rsRetVal doInjectMsg(uchar *szMsg, ratelimit_t *ratelimiter) {
    smsg_t *pMsg;
    struct syslogTime stTime;
    time_t ttGenTime;
    DEFiRet;

    datetime.getCurrTime(&stTime, &ttGenTime, TIME_IN_LOCALTIME);
    /* we now create our own message object and submit it to the queue */
    CHKiRet(msgConstructWithTime(&pMsg, &stTime, ttGenTime));
    MsgSetRawMsg(pMsg, (char *)szMsg, ustrlen(szMsg));
    MsgSetInputName(pMsg, pInputName);
    MsgSetFlowControlType(pMsg, injectmsgDelayMode);
    pMsg->msgFlags = NEEDS_PARSING | PARSE_HOSTNAME;
    MsgSetRcvFrom(pMsg, pRcvDummy);
    CHKiRet(MsgSetRcvFromIP(pMsg, pRcvIPDummy));
    CHKiRet(ratelimitAddMsg(ratelimiter, NULL, pMsg));

finalize_it:
    RETiRet;
}

/* submit a generated numeric-suffix message to the rsyslog core
 */
/** The hostname inserted into generated diagnostic messages.
 * 192.0.2.0/24 (TEST-NET-1) is reserved for documentation and examples per
 * RFC 5737, so using 192.0.2.8 avoids collisions with real-world systems.
 */
static const char diagDefaultHostname[] = "192.0.2.8";

static rsRetVal doInjectNumericSuffixMsg(int64_t iNum, ratelimit_t *ratelimiter) {
    uchar szMsg[1024];
    DEFiRet;
    snprintf((char *)szMsg, sizeof(szMsg) / sizeof(uchar), "<167>Mar  1 01:00:00 %s tag msgnum:%8.8" PRId64 ":",
             diagDefaultHostname, iNum);
    iRet = doInjectMsg(szMsg, ratelimiter);
    RETiRet;
}

static rsRetVal parseInt64Arg(const uchar *arg, const char *name, int64_t *outVal) {
    char *end = NULL;
    long long parsed = 0;
    DEFiRet;

    if (arg == NULL || *arg == '\0') {
        LogError(0, RS_RET_PARAM_ERROR, "imdiag: missing %s argument", name);
        ABORT_FINALIZE(RS_RET_PARAM_ERROR);
    }

    errno = 0;
    parsed = strtoll((const char *)arg, &end, 10);
    if (errno == ERANGE || end == (char *)arg || (end != NULL && *end != '\0')) {
        LogError(0, RS_RET_PARAM_ERROR, "imdiag: invalid %s value '%s'", name, arg);
        ABORT_FINALIZE(RS_RET_PARAM_ERROR);
    }

    *outVal = (int64_t)parsed;

finalize_it:
    RETiRet;
}

/* This function injects messages. Command format:
 * injectmsg <fromnbr> <number-of-messages>
 * injectmsg <fromnbr> <number-of-messages> <delay-between-messages-ms>
 * Additional trailing arguments are ignored for backward compatibility with
 * older testbench helpers.
 * rgerhards, 2009-05-27
 */
static rsRetVal injectMsg(uchar *pszCmd, tcps_sess_t *pSess) {
    uchar wordBuf[1024];
    int64_t iFrom, nMsgs;
    int64_t delayMs = 0;
    uchar *literalMsg;
    int64_t i;
    ratelimit_t *ratelimit = NULL;
    DEFiRet;

    literalMsg = NULL;

    memset(wordBuf, 0, sizeof(wordBuf));
    CHKiRet(ratelimitNew(&ratelimit, "imdiag", "injectmsg"));
    /* we do not check errors here! */
    getFirstWord(&pszCmd, wordBuf, sizeof(wordBuf), TO_LOWERCASE);
    if (ustrcmp(UCHAR_CONSTANT("literal"), wordBuf) == 0) {
        /* user has provided content for a message */
        ++pszCmd; /* ignore following space */
        CHKiRet(doInjectMsg(pszCmd, ratelimit));
        nMsgs = 1;
    } else { /* assume 2 args, (from_idx, count) */
        CHKiRet(parseInt64Arg(wordBuf, "from", &iFrom));
        getFirstWord(&pszCmd, wordBuf, sizeof(wordBuf), TO_LOWERCASE);
        CHKiRet(parseInt64Arg(wordBuf, "count", &nMsgs));
        getFirstWord(&pszCmd, wordBuf, sizeof(wordBuf), TO_LOWERCASE);
        if (wordBuf[0] != '\0') {
            CHKiRet(parseInt64Arg(wordBuf, "delay-ms", &delayMs));
            if (delayMs < 0 || delayMs > (int64_t)INT_MAX * 1000) {
                LogError(0, RS_RET_PARAM_ERROR, "imdiag: invalid delay-ms value '%s'", wordBuf);
                ABORT_FINALIZE(RS_RET_PARAM_ERROR);
            }
        }
        for (i = 0; i < nMsgs; ++i) {
            CHKiRet(doInjectNumericSuffixMsg(i + iFrom, ratelimit));
            if (delayMs > 0 && i + 1 < nMsgs) {
                srSleep((int)(delayMs / 1000), (int)((delayMs % 1000) * 1000));
            }
        }
    }
    CHKiRet(sendResponse(pSess, "%" PRId64 " messages injected\n", nMsgs));

    DBGPRINTF("imdiag: %" PRId64 " messages injected\n", nMsgs);

finalize_it:
    if (ratelimit != NULL) ratelimitDestruct(ratelimit);
    free(literalMsg);
    RETiRet;
}


/* This function waits until all queues are drained (size = 0)
 * To make sure it really is drained, we check multiple times. Otherwise we
 * may just see races. Note: it is important to ensure that the size
 * is zero multiple times in succession. Otherwise, we may just accidently
 * hit a situation where the queue isn't filled for a while (we have seen
 * this in practice, see https://github.com/rsyslog/rsyslog/issues/688).
 * Note: until 2014--07-13, this checked just the main queue. However,
 * the testbench was the sole user and checking all queues makes much more
 * sense. So we change function semantics instead of carrying the old
 * semantics over and crafting a new function. -- rgerhards
 */
static rsRetVal waitMainQEmpty(tcps_sess_t *pSess) {
    int iPrint = 0;
    int iPrintVerbosity = 500;  // 500 default
    int nempty = 0;
    static unsigned lastOverallQueueSize = 1;
    DEFiRet;

    while (1) {
        processImInternal();
        const unsigned OverallQueueSize = PREFER_FETCH_32BIT(iOverallQueueSize);
        if (OverallQueueSize == 0) {
            ++nempty;
        } else {
            if (OverallQueueSize > 500) {
                /* do a bit of extra sleep to not poll too frequently */
                srSleep(0, (OverallQueueSize > 2000) ? 900000 : 100000);
            }
            nempty = 0;
        }
        if (dbgTimeoutToStderr) { /* we abuse this setting a bit ;-) */
            if (OverallQueueSize != lastOverallQueueSize) {
                fprintf(stderr, "imdiag: wait q_empty: qsize %d nempty %d\n", OverallQueueSize, nempty);
                lastOverallQueueSize = OverallQueueSize;
            }
        }
        if (nempty > max_empty_checks) break;
        if (iPrint++ % iPrintVerbosity == 0)
            DBGPRINTF(
                "imdiag sleeping, wait queues drain, "
                "curr size %d, nempty %d\n",
                OverallQueueSize, nempty);
        srSleep(0, 100000); /* wait a little bit */
    }

    CHKiRet(sendResponse(pSess, "mainqueue empty\n"));
    DBGPRINTF("imdiag: mainqueue empty\n");

finalize_it:
    RETiRet;
}

